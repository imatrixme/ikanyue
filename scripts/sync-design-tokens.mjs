import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sourcePath = path.join(ROOT, 'design-system/brand-tokens.json');
const tokens = JSON.parse(await readFile(sourcePath, 'utf8'));
const checkOnly = process.argv.includes('--check');

const kebab = (value) => value.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`);
const px = (value) => `${value}px`;
const rem = (value) => `${value / 16}rem`;

function renderMiniappScss() {
    const lines = ['// Generated by scripts/sync-design-tokens.mjs. Do not edit.'];
    for (const [name, value] of Object.entries(tokens.color)) lines.push(`$ky-${kebab(name)}: ${value};`);
    lines.push('$ky-gold-soft: $ky-yellow-soft;', '');
    for (const [name, value] of Object.entries(tokens.radiusPx)) lines.push(`$ky-radius-${name}: ${px(value)};`);
    lines.push('');
    for (const [name, value] of Object.entries(tokens.spacingPx)) lines.push(`$ky-space-${name}: ${px(value)};`);
    lines.push('', `$ky-font-sans: ${tokens.typography.fontFamily};`);
    for (const [name, value] of Object.entries(tokens.shadow.miniapp)) lines.push(`$ky-shadow-${kebab(name)}: ${value};`);
    for (const [name, value] of Object.entries(tokens.typography.miniappSizePx)) lines.push(`$ky-font-size-${kebab(name)}: ${px(value)};`);
    for (const [name, value] of Object.entries(tokens.typography.weight)) lines.push(`$ky-font-weight-${name}: ${value};`);
    for (const [name, value] of Object.entries(tokens.typography.lineHeight)) lines.push(`$ky-leading-${name}: ${value};`);
    lines.push(
        `$ky-paragraph-spacing: $ky-${tokens.paragraph.miniappSpacingToken};`,
        `$ky-prose-spacing: $ky-${tokens.paragraph.miniappProseSpacingToken};`,
    );
    for (const [name, value] of Object.entries(tokens.motionMs)) lines.push(`$ky-motion-${name}: ${value}ms;`);
    return `${lines.join('\n')}\n`;
}

function renderMiniappTheme() {
    const colorEntries = ['blue', 'canvas', 'danger', 'gold', 'primary', 'primaryStrong', 'success', 'surface', 'textSecondary']
        .map((name) => `    ${name}: '${tokens.color[name]}',`)
        .join('\n');
    return `// Generated by scripts/sync-design-tokens.mjs. Do not edit.\nconst themeColors = Object.freeze({\n${colorEntries}\n    tab: '${tokens.color.textSecondary}',\n});\n\nconst immersivePageChrome = Object.freeze({\n    backgroundColor: themeColors.primary,\n    backgroundColorBottom: themeColors.canvas,\n    backgroundColorTop: themeColors.primary,\n    backgroundTextStyle: 'light',\n    navigationBarBackgroundColor: themeColors.primary,\n    navigationBarTextStyle: 'white',\n});\n\nconst canvasPageChrome = Object.freeze({\n    backgroundColor: themeColors.canvas,\n    backgroundColorBottom: themeColors.canvas,\n    backgroundColorTop: themeColors.canvas,\n    backgroundTextStyle: 'dark',\n});\n\nexport { canvasPageChrome, immersivePageChrome, themeColors };\n`;
}

