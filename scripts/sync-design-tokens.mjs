function renderTypeScript() {
    const payload = {
        breakpoints: tokens.foundation.breakpointPx,
        components: tokens.component,
        containers: tokens.foundation.containerPx,
        motion: tokens.foundation.motionMs,
        patterns: tokens.pattern,
        semanticColors: tokens.semantic.color,
        spacing: tokens.foundation.spacingPx,
        zIndex: tokens.foundation.zIndex,
    };
    return `// Generated by scripts/sync-design-tokens.mjs. Do not edit.\nexport const designTokens = Object.freeze(${JSON.stringify(payload, null, 2)} as const);\n`;
}

validateTokens();

const outputs = [
    [path.join(ROOT, 'ikanyue.taro3/src/styles/_brand.generated.scss'), renderMiniappScss(), true],
    [path.join(ROOT, 'ikanyue.taro3/src/styles/theme.mjs'), renderMiniappTheme(), true],
    [path.join(ROOT, 'ikanyue.admin/src/styles/brand.generated.css'), renderAdminCss(), true],
    [path.join(ROOT, 'ikanyue.admin/src/styles/brand.generated.ts'), renderTypeScript(), true],
    [path.join(ROOT, 'ikanyue.website/app/assets/css/brand.generated.css'), renderWebsiteCss(), false],
    [path.join(ROOT, 'ikanyue.website/app/utils/brand.generated.ts'), renderTypeScript(), false],
];

let stale = false;
for (const [target, content, required] of outputs) {
    const parentExists = await exists(path.dirname(path.dirname(target)));
    if (!required && !parentExists) continue;
    if (checkOnly) {
        const current = await readFile(target, 'utf8').catch(() => '');
        if (current !== content) {
            stale = true;
            console.error(`Outdated design tokens: ${path.relative(ROOT, target)}`);
        }
        continue;
    }
    await mkdir(path.dirname(target), { recursive: true });
    await writeFile(target, content);
    console.log(`Updated ${path.relative(ROOT, target)}`);
}

if (stale) process.exitCode = 1;
