const outputs = new Map([
    [path.join(ROOT, 'ikanyue.taro3/src/styles/_brand.generated.scss'), renderMiniappScss()],
    [path.join(ROOT, 'ikanyue.taro3/src/styles/theme.mjs'), renderMiniappTheme()],
    [path.join(ROOT, 'ikanyue.admin/src/styles/brand.generated.css'), renderAdminCss()],
]);

let stale = false;
for (const [target, content] of outputs) {
    if (checkOnly) {
        const current = await readFile(target, 'utf8').catch(() => '');
        if (current !== content) {
            stale = true;
            console.error(`Outdated design tokens: ${path.relative(ROOT, target)}`);
        }
        continue;
    }
    await mkdir(path.dirname(target), { recursive: true });
    await writeFile(target, content);
    console.log(`Updated ${path.relative(ROOT, target)}`);
}

if (stale) process.exitCode = 1;
