import { access, mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sourcePath = path.join(ROOT, 'design-system/brand-tokens.json');
const tokens = JSON.parse(await readFile(sourcePath, 'utf8'));
const checkOnly = process.argv.includes('--check');

const kebab = (value) => value.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`);
const px = (value) => `${value}px`;
const rem = (value) => `${value / 16}rem`;
const exists = (target) => access(target).then(() => true).catch(() => false);

function readToken(tokenPath) {
    return tokenPath.split('.').reduce((value, key) => value?.[key], tokens);
}

function validateTokens() {
    const required = [
        'meta.version',
        'foundation.color.green500',
        'foundation.typography.fontFamily',
        'foundation.typography.miniappSizePx.body',
        'foundation.typography.admin.body',
        'foundation.typography.website.body',
        'foundation.spacingPx.4',
        'foundation.radiusPx.md',
        'foundation.motionMs.fast',
        'foundation.breakpointPx.md',
        'foundation.zIndex.modal',
        'foundation.containerPx.content',
        'semantic.color.primary',
        'semantic.color.canvas',
        'semantic.color.focusRing',
        'semantic.color.immersiveSurface',
        'semantic.color.infoText',
        'semantic.paragraph.miniappSpacingToken',
        'component.controlHeightPx.default',
        'component.iconSizePx.md',
        'component.tableRowHeightPx.default',
        'component.navigationPx.adminSidebar',
        'component.overlayPx.dialogMd',
        'component.focus.widthPx',
        'pattern.musicTicketPx.notch',
        'pattern.editorialPx.sectionGapDesktop',
    ];
    const missing = required.filter((tokenPath) => readToken(tokenPath) === undefined);
    if (missing.length) throw new Error(`Missing required design tokens: ${missing.join(', ')}`);
    if (!tokens.meta.version.startsWith('2.')) throw new Error('Token source must use the 2.x schema version.');

    const pairs = [
        ['semantic.color.primary', 'foundation.color.green500'],
        ['semantic.color.primaryStrong', 'foundation.color.green600'],
        ['semantic.color.immersiveSurface', 'foundation.color.green600'],
        ['semantic.color.primaryPressed', 'foundation.color.green700'],
        ['semantic.color.primarySoft', 'foundation.color.green200'],
        ['semantic.color.primaryLine', 'foundation.color.green300'],
        ['semantic.color.primaryWash', 'foundation.color.green50'],
    ];
    for (const [semantic, foundation] of pairs) {
        if (readToken(semantic) !== readToken(foundation)) {
            throw new Error(`Design token alias drift: ${semantic} must match ${foundation}`);
        }
    }
}

function appendScale(lines, prefix, values, transform = String) {
    for (const [name, value] of Object.entries(values)) lines.push(`${prefix}${kebab(name)}: ${transform(value)};`);
}

function appendCssScale(lines, prefix, values, transform = String) {
    for (const [name, value] of Object.entries(values)) lines.push(`  ${prefix}${kebab(name)}: ${transform(value)};`);
}

function renderMiniappScss() {
    const { foundation, semantic, component, pattern } = tokens;
    const lines = ['// Generated by scripts/sync-design-tokens.mjs. Do not edit.'];
    appendScale(lines, '$ky-', semantic.color);
    lines.push('$ky-gold-soft: $ky-yellow-soft;', '');
    appendScale(lines, '$ky-radius-', foundation.radiusPx, px);
    lines.push('');
    appendScale(lines, '$ky-space-', foundation.spacingPx, px);
    lines.push('', `$ky-font-sans: ${foundation.typography.fontFamily};`);
    appendScale(lines, '$ky-shadow-', foundation.shadow.miniapp);
    appendScale(lines, '$ky-font-size-', foundation.typography.miniappSizePx, px);
    appendScale(lines, '$ky-font-weight-', foundation.typography.weight);
    appendScale(lines, '$ky-leading-', foundation.typography.lineHeight);
    lines.push(
        `$ky-paragraph-spacing: $ky-${semantic.paragraph.miniappSpacingToken};`,
        `$ky-prose-spacing: $ky-${semantic.paragraph.miniappProseSpacingToken};`,
    );
    appendScale(lines, '$ky-motion-', foundation.motionMs, (value) => `${value}ms`);
    appendScale(lines, '$ky-breakpoint-', foundation.breakpointPx, px);
    appendScale(lines, '$ky-z-', foundation.zIndex);
    appendScale(lines, '$ky-container-', foundation.containerPx, px);
    appendScale(lines, '$ky-control-height-', component.controlHeightPx, px);
    appendScale(lines, '$ky-icon-size-', component.iconSizePx, px);
    appendScale(lines, '$ky-ticket-', pattern.musicTicketPx, px);
    lines.push(`$ky-disabled-opacity: ${component.disabledOpacity};`);
    return `${lines.join('\n')}\n`;
}

function renderMiniappTheme() {
    const colors = tokens.semantic.color;
    const colorEntries = ['blue', 'canvas', 'danger', 'gold', 'immersiveSurface', 'primary', 'primaryStrong', 'success', 'surface', 'textSecondary']
        .map((name) => `    ${name}: '${colors[name]}',`)
        .join('\n');
    return `// Generated by scripts/sync-design-tokens.mjs. Do not edit.\nconst themeColors = Object.freeze({\n${colorEntries}\n    tab: '${colors.textSecondary}',\n});\n\nconst immersivePageChrome = Object.freeze({\n    backgroundColor: themeColors.immersiveSurface,\n    backgroundColorBottom: themeColors.canvas,\n    backgroundColorTop: themeColors.immersiveSurface,\n    backgroundTextStyle: 'light',\n    navigationBarBackgroundColor: themeColors.immersiveSurface,\n    navigationBarTextStyle: 'white',\n});\n\nconst canvasPageChrome = Object.freeze({\n    backgroundColor: themeColors.canvas,\n    backgroundColorBottom: themeColors.canvas,\n    backgroundColorTop: themeColors.canvas,\n    backgroundTextStyle: 'dark',\n});\n\nexport { canvasPageChrome, immersivePageChrome, themeColors };\n`;
}

